#!/usr/bin/env python3
"""Generate the unrolled order-4 M2L lane kernel (src/.../bem_coulomb_fmm_m2l_order4.f90)."""

from __future__ import annotations

import argparse
from pathlib import Path

ORDER = 4
LANES = 4
BLOCK = 7
OUTPUT = Path("src/physics/field_solver/fmm/internal/runtime/bem_coulomb_fmm_m2l_order4.f90")


def multi_indices(order: int) -> list[tuple[int, int, int]]:
    """Same order as build_multi_index_table: total degree, then the x and y exponents ascending."""
    return [
        (ax, ay, total - ax - ay)
        for total in range(order + 1)
        for ax in range(total + 1)
        for ay in range(total - ax + 1)
    ]


def generate() -> str:
    alpha = multi_indices(ORDER)
    deriv = {index: position + 1 for position, index in enumerate(multi_indices(2 * ORDER))}
    ncoef = len(alpha)
    nderiv = len(deriv)
    sums = [
        [deriv[tuple(a + b for a, b in zip(alpha[i], alpha[j]))] for j in range(ncoef)] for i in range(ncoef)
    ]
    names = ", ".join(f"acc{k + 1}" for k in range(BLOCK))
    out = [
        "!> Generated by tools/generate_m2l_order4_kernel.py; do not edit.",
        f"!! 展開次数 {ORDER}（係数 {ncoef}、微分 {nderiv}）の M2L の 1 step 分を {LANES} lane 同時に足す。",
        "module bem_coulomb_fmm_m2l_order4",
        "  use bem_kinds, only: dp",
        "  implicit none",
        "  private",
        "",
        "  public :: m2l_lane_step_order4",
        "",
        "contains",
        "",
        "  !> lane ごとに `acc(:, alpha) += coeff(:, beta)*deriv(:, alpha_beta_deriv_idx(alpha, beta))` を",
        "  !! beta の昇順に足す（`bem_coulomb_fmm_state_ops` の汎用ループと同じ順）。添字を定数に展開し、",
        f"  !! {BLOCK} 個の alpha の {LANES} lane 分をレジスタに置いたまま beta を回す。",
        "  pure subroutine m2l_lane_step_order4(coeff, deriv, acc)",
        f"    real(dp), intent(in) :: coeff({LANES}, {ncoef}), deriv({LANES}, {nderiv})",
        f"    real(dp), intent(inout) :: acc({LANES}, {ncoef})",
        f"    real(dp), dimension({LANES}) :: {names}",
        "",
    ]
    for base in range(0, ncoef, BLOCK):
        block = list(range(base, min(base + BLOCK, ncoef)))
        for k, i in enumerate(block):
            out.append(f"    acc{k + 1} = acc(:, {i + 1})")
        for j in range(ncoef):
            for k, i in enumerate(block):
                out.append(f"    acc{k + 1} = acc{k + 1} + coeff(:, {j + 1})*deriv(:, {sums[i][j]})")
        for k, i in enumerate(block):
            out.append(f"    acc(:, {i + 1}) = acc{k + 1}")
    out += ["  end subroutine m2l_lane_step_order4", "", "end module bem_coulomb_fmm_m2l_order4", ""]
    return "\n".join(out)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the generated kernel is stale")
    args = parser.parse_args()
    path = Path(__file__).resolve().parents[1] / OUTPUT
    text = generate()
    if args.check:
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            raise SystemExit(f"{OUTPUT} is stale; run tools/generate_m2l_order4_kernel.py")
        return
    path.write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
